import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";

import { describe, expect, it } from "vitest";

import { paletteColors } from "@/internal/states";

import { SYS_PREFIX, toVarName } from "../../tokens/naming";
import { OFF_GRID } from "../../tokens/offGrid";
import { read as readRepo, walk } from "../test/contract-utils";

const stylesRoot = path.resolve(process.cwd(), "src/styles");
const read = (file: string) => readFileSync(path.join(stylesRoot, file), "utf8");

describe("generated token styles", () => {
  it("give every space step a unit, so it adds to a length inside calc()", () => {
    // `calc(100% + var(--prime-space-0))` with a unitless 0 is invalid and drops the declaration.
    const steps = [...read("tokens.css").matchAll(/--prime-ref-space-[\w-]+:\s*([^;]+);/g)];
    expect(steps.length).toBeGreaterThan(0);
    expect(steps.map((m) => m[1].trim()).filter((v) => !/[a-z%]$/.test(v))).toEqual([]);
  });

  it("are generated and expose the semantic contract", () => {
    const tokensCss = read("tokens.css");
    const light = read("theme-light.css");
    const dark = read("theme-dark.css");

    for (const css of [tokensCss, light, dark]) {
      expect(css).toContain("AUTO-GENERATED by scripts/build-tokens.ts");
    }
    for (const name of [
      "--prime-color-layer-0-bg",
      "--prime-color-layer-4-fill",
      "--prime-color-layer-floating-selected",
      "--prime-color-focus-ring",
      "--prime-control-xs-height",
      "--prime-control-xl-height",
      "--prime-text-body-m-size",
      "--prime-space-4",
      "--prime-z-overlay",
      "--prime-z-toast",
      "--prime-color-palette-teal-soft",
    ]) {
      expect(light).toContain(`${name}:`);
    }
    expect(dark).toContain("--prime-color-layer-0-bg:");
    expect(dark).toContain("--prime-shadow-overlay:");
  });

  it("has no semantic token that the kit does not use", () => {
    const srcRoot = path.resolve(process.cwd(), "src");
    const generated = new Set(["tokens.css", "theme-light.css", "theme-dark.css"]);
    const sources = (readdirSync(srcRoot, { recursive: true }) as string[])
      .filter((file) => /\.(css|tsx?)$/.test(file) && !/\.test\.tsx?$/.test(file))
      .filter((file) => !generated.has(path.basename(file)))
      .map((file) => readFileSync(path.join(srcRoot, file), "utf8"))
      .join("\n");
    const declared = new Set(
      [read("theme-light.css"), read("theme-dark.css")].flatMap((css) =>
        [...css.matchAll(/^\s+(--prime-[a-z0-9-]+):/gm)].map((m) => m[1]),
      ),
    );
    const unused = [...declared].filter(
      (name) => !new RegExp(`${name}(?![a-z0-9-])`).test(sources),
    );
    expect(unused).toEqual([]);
  });

  it("maps every surface depth to its row of layer tokens", () => {
    const globals = read("globals.css");
    for (const depth of ["1", "2", "3", "4", "floating", "floating-1", "floating-2"]) {
      expect(globals, depth).toContain(`[data-depth="${depth}"] {`);
    }
    for (const row of ["0", "1", "2", "3", "4", "floating", "floating1", "floating2"]) {
      for (const role of ["bg", "fill", "fill-hover", "selected"]) {
        expect(globals, `${row} ${role}`).toContain(`var(--prime-color-layer-${row}-${role});`);
      }
    }
  });

  // `data-depth` belongs to the surface ladder: a component that reuses it for its own meaning
  // (a tree level, a stack index) would silently swap the context colors of everything inside.
  it("selects data-depth only in globals.css", () => {
    const srcRoot = path.resolve(process.cwd(), "src");
    const offenders = (readdirSync(srcRoot, { recursive: true }) as string[])
      .filter((file) => file.endsWith(".css") && path.basename(file) !== "globals.css")
      .filter((file) => readFileSync(path.join(srcRoot, file), "utf8").includes("[data-depth"));
    expect(offenders).toEqual([]);
  });

  // An app sets the container's insets once (`--prime-safe-area-*`, a Telegram Mini App in full
  // screen): a part that read `env()` itself would stay under the host's header.
  it("reads env(safe-area-inset-*) only in globals.css, through --prime-safe-area-*", () => {
    const globals = read("globals.css");
    for (const side of ["top", "right", "bottom", "left"]) {
      expect(globals, side).toContain(
        `--prime-safe-area-${side}: env(safe-area-inset-${side}, var(--prime-space-0));`,
      );
    }
    const offenders = walk("src", /\.css$/)
      .filter((file) => file !== "src/styles/globals.css")
      .filter((file) => readRepo(file).includes("safe-area-inset"));
    expect(offenders).toEqual([]);
  });

  it("maps every palette hue in internal/palette", () => {
    const css = readFileSync(
      path.resolve(process.cwd(), "src/internal/palette.module.css"),
      "utf8",
    );
    for (const color of paletteColors.filter((hue) => hue !== "gray")) {
      expect(css, color).toContain(`.hue[data-color="${color}"] {`);
      for (const role of ["soft", "text", "solid", "solid-fg"]) {
        expect(css, `${color} ${role}`).toContain(`var(--prime-color-palette-${color}-${role});`);
      }
    }
  });

  it("keeps every space token on the 4px grid", () => {
    const values = [...read("tokens.css").matchAll(/--prime-ref-space-\d+: ([\d.]+)rem;/g)].map(
      (m) => Number(m[1]),
    );
    expect(values.length).toBeGreaterThan(8);
    for (const rem of values) {
      expect((rem * 16) % 4).toBe(0);
    }
  });

  it("reads only generated tokens and declared context variables (tokens-reads)", () => {
    const generated = ["tokens.css", "theme-light.css", "theme-dark.css"].map(read).join("\n");
    const css = walk("src", /\.css$/).filter(
      (file) => !/^src\/styles\/(tokens|theme-light|theme-dark)\.css$/.test(file),
    );
    const code = walk("src", /\.tsx?$/).filter(
      (file) => !/\.test\.tsx?$|\/api\.ts$|\.api\.ts$|\/examples\//.test(file),
    );
    // The context list: the variables globals.css and controls.css declare for every subtree
    // (`--prime-color-layer-current`, the field context…). A component never invents a
    // `--prime-*` name of its own, in CSS or from TS.
    const declared = new Set(
      [generated, readRepo("src/styles/globals.css"), readRepo("src/styles/controls.css")].flatMap(
        (text) => [...text.matchAll(/(--prime-[\w-]+)\s*:/g)].map((m) => m[1]),
      ),
    );
    const offenders = new Set<string>();
    for (const file of [...css, ...code]) {
      const text = readRepo(file);
      const reads = file.endsWith(".css")
        ? [...text.matchAll(/var\((--prime-[\w-]+)/g)]
        : [...text.matchAll(/["'`(](--prime-[\w-]*[\w])["'`),]/g)];
      for (const m of reads) {
        if (!declared.has(m[1]) && !m[1].endsWith("-")) offenders.add(`${file}: ${m[1]}`);
      }
    }
    expect([...offenders], "tokens-reads").toEqual([]);
  });

  // The exceptions are the list of foundation §1 rule 2, which `tokens:build` writes from
  // `tokens/offGrid.ts`.
  it("keeps semantic heights, widths, paddings and gaps on the 4px grid, but for foundation's list", () => {
    const rule = readRepo("docs/foundation.md").split("<!-- off-grid:start -->")[1] ?? "";
    const listed = [
      ...(rule.split("<!-- off-grid:end -->")[0] ?? "").matchAll(/^\s+- `(--prime-[\w-]+)`/gm),
    ].map((m) => m[1]);
    expect(listed).toEqual(Object.keys(OFF_GRID).map((key) => toVarName(key, SYS_PREFIX)));
    const tokens = read("tokens.css");
    // The touch block is the platform's own geometry (the iOS Switch, 51×31): it is not on the grid.
    const theme = read("theme-light.css").split("@media (pointer: coarse)")[0] ?? "";
    const refs = new Map(
      [...tokens.matchAll(/^\s+(--prime-ref-[\w-]+):\s*([^;]+);/gm)].map((m) => [m[1], m[2]]),
    );
    const px = (value: string): number | null => {
      const ref = value.match(/^var\((--prime-ref-[\w-]+)\)$/)?.[1];
      const raw = ref ? (refs.get(ref) ?? "") : value;
      if (raw === "0") return 0;
      const rem = raw.match(/^(-?\d*\.?\d+)rem$/)?.[1];
      if (rem) return Number(rem) * 16;
      const pixels = raw.match(/^(-?\d*\.?\d+)px$/)?.[1];
      return pixels ? Number(pixels) : null;
    };
    const offenders: string[] = [];
    for (const m of theme.matchAll(/^\s+(--prime-[\w-]+):\s*([^;]+);/gm)) {
      const [, name, value] = m;
      if (!/-(height|width|padding(-[a-z]+)?|gap)$/.test(name)) continue;
      if (/(text|line-height|border|icon|radius|font|stroke|ring)/.test(name)) continue;
      const value_ = px(value.trim());
      if (value_ !== null && value_ % 4 !== 0 && !listed.includes(name)) {
        offenders.push(`${name}: ${value_}px`);
      }
    }
    expect(offenders).toEqual([]);
  });

  // Foundation §5: on a coarse pointer the reading text, the titles of surfaces and the text of
  // every control tier step up; control heights, headings and badge text stay.
  it("steps the type and the control marks up under (pointer: coarse) and keeps every height (touch-type)", () => {
    const theme = read("theme-light.css");
    const refs = new Map(
      [...read("tokens.css").matchAll(/^\s+(--prime-ref-[\w-]+):\s*([^;]+);/gm)].map((m) => [
        m[1],
        m[2],
      ]),
    );
    const px = (value: string) =>
      Number(
        (refs.get(value.match(/^var\((--prime-ref-[\w-]+)\)$/)?.[1] ?? "") ?? value).replace(
          "rem",
          "",
        ),
      ) * 16;
    const rem = (value: string | undefined) => Number((value ?? "").replace("rem", "")) * 16;
    const decls = (css: string) =>
      new Map([...css.matchAll(/^\s+(--prime-[\w-]+):\s*([^;]+);/gm)].map((m) => [m[1], m[2]]));
    const [base, touchCss] = theme.split("@media (pointer: coarse) {");
    expect(touchCss, "the touch block").toBeDefined();
    expect(touchCss).toContain(':root,\n  :root[data-theme="light"],\n  [data-theme="light"] {');
    const desktop = decls(base);
    const touch = decls(touchCss);

    const grows = [
      ...["body-s", "body-m", "title-xs", "title-s", "code"].map(
        (role) => `--prime-text-${role}-size`,
      ),
      "--prime-control-s-text-size",
      "--prime-control-s-label-size",
      "--prime-bottom-nav-label-size",
      "--prime-bottom-nav-floating-label-size",
      "--prime-control-m-text-size",
      "--prime-control-m-label-size",
      ...["l", "xl"].flatMap((tier) => [
        `--prime-control-${tier}-label-size`,
        `--prime-control-${tier}-hint-size`,
      ]),
      ...["s", "m", "l", "xl"].map((tier) => `--prime-badge-${tier}-text-size`),
    ];
    const tiers = ["xs", "s", "m", "l", "xl"];
    for (const name of grows) {
      const value = touch.get(name);
      expect(value, name).toBeDefined();
      expect(px(value ?? ""), name).toBeGreaterThan(px(desktop.get(name) ?? ""));
    }
    // Control text is one size per tier on touch: m 16, l and xl 17, s 14, xs 12 (no separate field floor).
    expect(touch.get("--prime-control-m-text-size")).toBe("var(--prime-ref-font-size-16)");
    expect(touch.get("--prime-control-m-line-height")).toBe("var(--prime-ref-font-line-height-24)");
    for (const t of ["l", "xl"])
      expect(touch.get(`--prime-control-${t}-text-size`)).toBe("var(--prime-ref-font-size-17)");
    expect(touch.has("--prime-control-xs-text-size")).toBe(false);
    for (const [name, value] of touch) {
      if (
        /^--prime-(switch-\w+-(width|height|thumb)|control-\w+-(icon|choice|thumb)|badge-\w+-icon)$/.test(
          name,
        )
      )
        continue;
      expect(name, "type only").toMatch(/-(size|line-height)$/);
      expect(name, "no box").not.toMatch(
        /^--prime-badge-\w+-(height|padding|gap|radius)|heading|display/,
      );
      if (name.endsWith("line-height")) expect(px(value) % 4, name).toBe(0);
      // Badge and BottomNav labels sit in fixed one-line boxes: their line height is not stepped.
      if (!name.endsWith("-size") || /^--prime-(badge|bottom-nav)-/.test(name)) continue;
      // Every grown size keeps a line height of at least 1.2 of it (its own or the desktop one).
      const lhName = name.replace(/(text-)?size$/, "line-height");
      const lh = touch.get(lhName) ?? desktop.get(lhName);
      expect(px(lh ?? ""), lhName).toBeGreaterThanOrEqual(px(value) * 1.2);
    }
    // The marks: the Switch keeps the iOS proportions, the choice box and the slider thumb grow.
    const SWITCH = {
      s: [36, 22, 18],
      m: [44, 26, 22],
      l: [48, 28, 24],
      xl: [51, 31, 27],
    } as const;
    for (const [tier, [w, h, thumb]] of Object.entries(SWITCH)) {
      expect(rem(touch.get(`--prime-switch-${tier}-width`) ?? ""), `${tier} width`).toBeCloseTo(
        w,
        0,
      );
      expect(rem(touch.get(`--prime-switch-${tier}-height`) ?? ""), `${tier} height`).toBe(h);
      expect(rem(touch.get(`--prime-switch-${tier}-thumb`) ?? ""), `${tier} thumb`).toBe(thumb);
    }
    // The glyphs step with the text and stay inside their box.
    const ICONS = { xs: 16, s: 18, m: 18, l: 22, xl: 22 } as const;
    for (const [tier, size] of Object.entries(ICONS)) {
      expect(rem(touch.get(`--prime-control-${tier}-icon`) ?? ""), `${tier} icon`).toBe(size);
    }
    const BADGE_ICONS = { s: 14, m: 16, xl: 18 } as const;
    for (const [tier, size] of Object.entries(BADGE_ICONS)) {
      expect(rem(touch.get(`--prime-badge-${tier}-icon`) ?? ""), `${tier} badge icon`).toBe(size);
    }
    expect(touch.has("--prime-badge-xs-icon") || touch.has("--prime-badge-l-icon")).toBe(false);
    for (const tier of tiers) {
      const height = px(desktop.get(`--prime-control-${tier}-height`) ?? "");
      const thumb = touch.get(`--prime-control-${tier}-thumb`);
      expect(rem(thumb), `${tier} thumb`).toBeGreaterThan(
        px(desktop.get(`--prime-control-${tier}-thumb`) ?? ""),
      );
      expect(rem(thumb), `${tier} thumb fits the height`).toBeLessThan(height);
      const choice =
        touch.get(`--prime-control-${tier}-choice`) ??
        desktop.get(`--prime-control-${tier}-choice`);
      expect(
        choice?.endsWith("rem") ? rem(choice) : px(choice ?? ""),
        `${tier} choice`,
      ).toBeLessThanOrEqual(24);
      expect(touch.has(`--prime-control-${tier}-track`), `${tier} track stays`).toBe(false);
      expect(touch.has(`--prime-control-${tier}-height`), `${tier} height stays`).toBe(false);
    }
    // The text grows inside the tier's box: a control's line height stays under its height.
    for (const tier of tiers) {
      const lh =
        touch.get(`--prime-control-${tier}-line-height`) ??
        desktop.get(`--prime-control-${tier}-line-height`);
      expect(px(lh ?? ""), tier).toBeLessThan(
        px(desktop.get(`--prime-control-${tier}-height`) ?? ""),
      );
    }
  });
});
