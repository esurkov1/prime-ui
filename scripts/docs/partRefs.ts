/**
 * `src/test/part-refs.generated.ts`: the ref of every part as its `api.ts` states it — the lead
 * of the part's `en` (`` `ref` → `HTMLButtonElement`. ``, `No DOM, no ref.`). The part-refs test
 * checks each entry against the TypeScript props of the exported part, so the ref line of the
 * docs and the code cannot drift.
 */
import type { ApiPart, ComponentApi } from "./componentApi";

/** A part name that resolves to an export: `Button`, `Button.Root`. */
const EXPORT_NAME = /^[A-Z]\w*(\.[A-Z]\w*)?$/;

/** The element types a ref line names, in order (`HTMLHeadingElement` / `HTMLParagraphElement`). */
function elementsOf(line: string): string[] {
  return [...line.matchAll(/`((?:HTML|SVG)\w*Element)`/g)].map((m) => m[1]);
}

/**
 * The ref of a part: the element type names its ref line gives (one per name of a `A · B` part,
 * or one for all), `["Element"]` for "the element" (the rendered element varies), `null` for a
 * part with no DOM or no ref, `undefined` when the lead names no ref at all.
 */
export function refOf(part: ApiPart): (string[] | null)[] | undefined {
  const names = part.name.split(" · ");
  const lead = part.en.split(/\.\s/)[0];
  if (/^No (DOM|ref)\b/.test(part.en)) return names.map(() => null);
  const arrow = lead.match(/`(?:forward)?[Rr]ef` → (.*)$/);
  if (!arrow) return undefined;
  const elements = elementsOf(arrow[1]);
  if (elements.length === 0) return names.map(() => ["Element"]);
  if (elements.length === names.length) return elements.map((element) => [element]);
  return names.map(() => elements);
}

/** The generated module: `PART_REFS` by part name, in component order. */
export function renderPartRefs(apis: { base: string; dir: string; api: ComponentApi }[]): string {
  const rows: string[] = [];
  const seen = new Set<string>();
  for (const { api } of apis) {
    for (const part of api.parts) {
      const refs = refOf(part);
      if (!refs) continue;
      part.name.split(" · ").forEach((name, index) => {
        if (!EXPORT_NAME.test(name) || seen.has(name)) return;
        seen.add(name);
        const ref = refs[index];
        const key = name.includes(".") ? JSON.stringify(name) : name;
        rows.push(`  ${key}: ${ref ? JSON.stringify(ref).replaceAll(",", ", ") : "null"},`);
      });
    }
  }
  return [
    "// Generated by `bun run docs:build` from the ref line of every api.ts part. Do not edit.",
    "",
    "/** The element types each part's ref reaches (`null`: the part takes no ref). */",
    "export const PART_REFS = {",
    ...rows,
    "} as const;",
    "",
  ].join("\n");
}
